export default function Archive() {
  return (
    <Section id="archive" number="05" title="Encrypted Download and the .cblock Archive">
      <p>
        After all blocks are encrypted, they are packaged together with metadata into a standard ZIP archive bearing the <code>.cblock</code> extension. The archive is stored uncompressed using <code>ZIP_STORED</code> so that block boundaries remain predictable.
      </p>
      <p>
        Inside the <code>.cblock</code> archive, the structure is organized as:
      </p>
      <ul>
        <li>
          <code>manifest.json</code> at the archive root — a canonical JSON file serialized with sorted keys and compact separators. It contains:
          <ul>
            <li><code>block_size</code> — block size in bytes (65536)</li>
            <li><code>count</code> — total block count</li>
            <li><code>iterations</code> — PBKDF2 iteration count (600000)</li>
            <li><code>name</code> — original file name</li>
            <li><code>salt</code> — 16-byte random salt stored as 32 hexadecimal characters</li>
            <li><code>sha256</code> — SHA-256 digest of original plaintext stored as 64 hexadecimal characters</li>
            <li><code>size</code> — original file size in bytes</li>
            <li><code>version</code> — schema version (1)</li>
          </ul>
        </li>
        <li>
          <code>blocks/000000.enc</code>, <code>blocks/000001.enc</code>, etc. — sequentially numbered encrypted block files containing the nonce, ciphertext, and tag.
        </li>
      </ul>
      <p>
        The manifest metadata fields (filename, file size, block count, salt, SHA-256 digest) are stored as plaintext JSON in the manifest. The file CONTENTS themselves are encrypted exclusively inside the block files.
      </p>
      <p>
        When generated by the local web application, the archive is saved locally under the <code>data/</code> directory using a randomly generated 32-character hexadecimal identifier.
      </p>

      <Figure04 />
    </Section>
  )
}
